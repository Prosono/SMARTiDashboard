"""Rendezvous for unconfigured hubs. No hub credentials are installed in advance."""

import base64
import hashlib
import json
import secrets
import time
from uuid import UUID

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from fastapi import HTTPException, Request
from pydantic import BaseModel, Field


class EnrollmentPoll(BaseModel):
    device: UUID
    secret: str = Field(pattern=r"^[A-Za-z0-9_-]{43,128}$", repr=False)
    fingerprint: str = Field(pattern=r"^[a-f0-9]{64}$")
    version: str = Field(max_length=40)
    users: int = Field(ge=0)
    ha_connected: bool


def install_enrollment(app, db, throttle, provisioning_secret):
    cipher = AESGCM(hashlib.sha256(("hub-enrollment:" + provisioning_secret).encode()).digest())
    with db() as c:
        c.executescript("""
        CREATE TABLE IF NOT EXISTS hub_enrollments(
          device TEXT PRIMARY KEY, secret_hash TEXT NOT NULL, fingerprint TEXT NOT NULL,
          health TEXT NOT NULL, seen REAL NOT NULL, home TEXT UNIQUE REFERENCES homes(id),
          delivery TEXT);
        """)

    def seal(device, payload):
        nonce = secrets.token_bytes(12)
        encrypted = cipher.encrypt(nonce, json.dumps(payload).encode(), device.encode())
        return base64.urlsafe_b64encode(nonce + encrypted).decode()

    @app.post("/api/enrollment/poll")
    def poll(body: EnrollmentPoll, request: Request):
        # This secret is generated by the hub, stays off Bonjour and is never sent to a browser.
        device, now = str(body.device), time.time()
        hashed = hashlib.sha256(body.secret.encode()).hexdigest()
        if device != str(UUID(bytes=bytes.fromhex(hashed)[:16], version=4)):
            # A LAN observer cannot pre-register someone else's broadcast ID with a different secret.
            raise HTTPException(403, "enrollment_rejected")
        health = json.dumps({"version": body.version, "users": body.users, "ha_connected": body.ha_connected})
        # Registration is throttled separately: valid polling must survive normal setup delays.
        with db() as c:
            known = c.execute("SELECT secret_hash FROM hub_enrollments WHERE device=?", (device,)).fetchone()
        if not known:
            throttle("enroll-new:" + request.client.host)
        elif not secrets.compare_digest(known["secret_hash"], hashed):
            throttle("enroll-invalid:" + request.client.host)
            raise HTTPException(403, "enrollment_rejected")
        with db() as c:
            c.execute("BEGIN IMMEDIATE")
            row = c.execute("SELECT * FROM hub_enrollments WHERE device=?", (device,)).fetchone()
            if row and (
                not secrets.compare_digest(row["secret_hash"], hashed)
                or row["fingerprint"] != body.fingerprint
            ):
                raise HTTPException(403, "enrollment_rejected")
            if not row:
                if body.users:
                    raise HTTPException(409, "existing_users")
                c.execute("DELETE FROM hub_enrollments WHERE home IS NULL AND seen<?", (now - 86400,))
                if (
                    c.execute("SELECT COUNT(*) FROM hub_enrollments WHERE home IS NULL").fetchone()[0]
                    >= 10000
                ):
                    raise HTTPException(503, "enrollment_busy")
                c.execute(
                    "INSERT INTO hub_enrollments(device,secret_hash,fingerprint,health,seen) VALUES(?,?,?,?,?)",
                    (device, hashed, body.fingerprint, health, now),
                )
            else:
                c.execute("UPDATE hub_enrollments SET health=?,seen=? WHERE device=?", (health, now, device))
                if row["delivery"]:
                    raw = base64.urlsafe_b64decode(row["delivery"])
                    identity = json.loads(cipher.decrypt(raw[:12], raw[12:], device.encode()))
                    return {"identity": identity}
            return {"waiting": True}

    def bind(c, row, device):
        """Called only after account, CSRF, printed QR and PIN validation, in the claim transaction."""
        pending = c.execute("SELECT * FROM hub_enrollments WHERE device=?", (device,)).fetchone()
        if not pending or pending["seen"] < time.time() - 100:
            raise HTTPException(409, "enrollment_offline")
        if pending["home"]:
            if pending["home"] != row["home"]:
                raise HTTPException(409, "device_already_linked")
            return
        if row["owner"] or row["fingerprint"]:
            # Never overwrite an already personalized/owned installation with a different physical hub.
            raise HTTPException(409, "hub_already_personalized")
        health = json.loads(pending["health"])
        if health["users"] or not health["ha_connected"]:
            raise HTTPException(409, "enrollment_not_ready")
        credential = secrets.token_urlsafe(48)
        c.execute(
            "UPDATE homes SET credential=? WHERE id=?",
            (hashlib.sha256(credential.encode()).hexdigest(), row["home"]),
        )
        c.execute(
            "UPDATE factory_hubs SET fingerprint=?,heartbeat=?,seen=?,phase='ready' WHERE home=?",
            (pending["fingerprint"], pending["health"], pending["seen"], row["home"]),
        )
        c.execute(
            "UPDATE hub_enrollments SET home=?,delivery=? WHERE device=?",
            (row["home"], seal(device, {"installation_id": row["home"], "credential": credential}), device),
        )

    return bind
