import { test, expect } from "../../frontend/node_modules/@playwright/test";

test("factory reset is advanced-only, explains pairing limits and stays blocked without a provider", async ({page}) => {
  await page.goto('/');
  await page.getByLabel('Brukernavn',{exact:true}).fill('tester');
  await page.getByLabel('Passord',{exact:true}).fill('test-password-not-for-live');
  await page.getByRole('button',{name:'Logg inn',exact:true}).click();
  await page.getByRole('button',{name:'Innstillinger',exact:true}).first().click();
  await page.getByRole('button',{name:/^Avansert/}).click();
  await page.getByRole('navigation',{name:'Innstillingskategorier'}).getByRole('button',{name:'System',exact:true}).click();
  await page.locator('.settings-advanced > summary').click();
  await page.getByRole('button',{name:'Se hva som tilbakestilles'}).click();
  const dialog=page.getByRole('dialog',{name:'Tilbakestill huben?'});
  await expect(dialog).toContainText('Paringer fjernes ikke');
  await expect(dialog.getByRole('checkbox',{name:'Slett alle sikkerhetskopier', exact:false})).not.toBeChecked();
  const radio = dialog.getByRole('radio').first();
  expect((await radio.boundingBox())!.width).toBeLessThan(30);
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await expect(dialog).toContainText('Ingen data er slettet');
  await dialog.screenshot({path:`/tmp/smarti-reset-top-${test.info().project.name}.png`});
  await dialog.getByRole('checkbox',{name:'Slett alle sikkerhetskopier',exact:false}).scrollIntoViewIfNeeded();
  await dialog.screenshot({path:`/tmp/smarti-reset-backups-${test.info().project.name}.png`});
  expect(await dialog.locator('.dashboard-settings-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await dialog.getByLabel('Sikkerhetskopi',{exact:true}).selectOption('skip');
  await dialog.getByRole('checkbox').nth(0).check();
  await dialog.getByRole('checkbox').nth(1).check();
  await dialog.getByLabel('Skriv RESET HUB for å bekrefte').fill('RESET HUB');
  await expect(dialog.getByRole('button',{name:'Start tilbakestilling'})).toBeDisabled();
  await dialog.screenshot({path:`/tmp/smarti-factory-reset-${test.info().project.name}.png`});
  await dialog.getByRole('button',{name:'Avbryt',exact:true}).click();
  await page.getByRole('button',{name:'Se hva som tilbakestilles'}).click();
  await expect(page.getByLabel('Passordet til din administratorkonto')).toHaveCount(0);
  await page.getByRole('button',{name:'Avbryt',exact:true}).click();
  await page.getByRole('button',{name:/^Normal/}).click();
  await expect(page.locator('.factory-reset-panel')).toHaveCount(0);
});

test("reset request shows durable incomplete report instead of success", async ({page}) => {
  await page.goto('/');
  await page.getByLabel('Brukernavn',{exact:true}).fill('tester');
  await page.getByLabel('Passord',{exact:true}).fill('test-password-not-for-live');
  await page.getByRole('button',{name:'Logg inn',exact:true}).click();
  await page.getByRole('button',{name:'Innstillinger',exact:true}).first().click();
  await page.getByRole('button',{name:/^Avansert/}).click();
  let job:any=null;let writes=0;
  await page.route('**/api/manage/settings/factory-reset', async route => {
    if(route.request().method()==='POST'){
      writes++;const body=route.request().postDataJSON();
      expect(body.acknowledge_manual_cleanup).toBe(true);
      expect(body.password).toBeUndefined();
      expect(body.delete_backups).toBe(true);
      expect(body.ownership).toBe("release_owner");
      expect(body.acknowledge_release).toBe(true);
      job={id:body.request_id,status:'incomplete',step:'finished',error:'',results:[{kind:'zigbee',name:'Testlampe',status:'done',reason:''},{kind:'manual',name:'Z-Wave',status:'manual',reason:'zwave_exclusion_required'}]};
      return route.fulfill({status:202,json:job});
    }
    return route.fulfill({json:{ready:true,full:true,blockers:[],job}});
  });
  await page.getByRole('navigation',{name:'Innstillingskategorier'}).getByRole('button',{name:'System',exact:true}).click();
  await page.locator('.settings-advanced > summary').click();
  await page.getByRole('button',{name:'Se hva som tilbakestilles'}).click();
  const dialog=page.getByRole('dialog',{name:'Tilbakestill huben?'});
  await dialog.getByRole('radio',{name:'Klargjør for ny eier – fjern fra kontoen'}).check();
  await expect(dialog).toContainText('Den trykte QR-koden beholdes');
  await dialog.getByLabel('Sikkerhetskopi',{exact:true}).selectOption('saved');
  for(const checkbox of await dialog.getByRole('checkbox').all()) await checkbox.check();
  await dialog.getByLabel('Skriv RESET HUB for å bekrefte').fill('RESET HUB');
  await dialog.getByRole('button',{name:'Start tilbakestilling',exact:true}).click();
  await expect(dialog).toContainText('Tilbakestillingen er ikke fullført');
  await expect(dialog).toContainText('Må følges opp manuelt');
  await expect(dialog).toContainText('Testlampe');
  expect(writes).toBe(1);
  await dialog.getByRole('button',{name:'Lukk',exact:true}).click();
  await page.getByRole('button',{name:'Se hva som tilbakestilles'}).click();
  await expect(page.getByRole('dialog')).toContainText('Tilbakestillingen er ikke fullført');
  expect(writes).toBe(1);
});

test("reset shows one live stage without the operation list and respects reduced motion", async ({page}) => {
  await page.goto('/');
  await page.getByLabel('Brukernavn',{exact:true}).fill('tester');
  await page.getByLabel('Passord',{exact:true}).fill('test-password-not-for-live');
  await page.getByRole('button',{name:'Logg inn',exact:true}).click();
  await page.getByRole('button',{name:'Innstillinger',exact:true}).first().click();
  await page.getByRole('button',{name:/^Avansert/}).click();
  let step='inventory'; let offline=false;
  await page.route('**/api/manage/settings/factory-reset', route => offline ? route.abort() : route.fulfill({json:{ready:false,blockers:[],job:{id:'running-reset',status:'running',step,error:'',results:[{kind:'full_reset',name:'Intern detalj',status:'running',reason:''}]}}}));
  await page.getByRole('navigation',{name:'Innstillingskategorier'}).getByRole('button',{name:'System',exact:true}).click();
  await page.locator('.settings-advanced > summary').click();
  await page.getByRole('button',{name:'Se hva som tilbakestilles'}).click();
  const dialog=page.getByRole('dialog',{name:'Tilbakestill huben?'});
  await expect(dialog.locator('.factory-reset-progress').getByRole('status')).toHaveText('Gjør huben klar');
  await expect(dialog.locator('.factory-reset-results')).toHaveCount(0);
  step='full_reset';
  await expect(dialog.locator('.factory-reset-progress').getByRole('status')).toHaveText('Tilbakestiller hjemmet',{timeout:10000});
  await dialog.screenshot({path:`/tmp/smarti-reset-loading-${test.info().project.name}.png`});
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(dialog.locator('.factory-reset-orbit span')).toHaveCSS('animation-name','none');
  offline=true;
  await expect(dialog.locator('.factory-reset-progress').getByRole('status')).toHaveText('Venter på kontakt med huben',{timeout:20000});
  await expect(dialog).toContainText('Vi kan ikke bekrefte fremdriften akkurat nå');
});
